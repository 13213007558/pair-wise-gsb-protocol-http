# frozen_string_literal: true

require_relative "../delta"

module Protocol
	module HTTP
		module Delta
			# A minimal VCDIFF (RFC 3284) encoder and decoder.
			#
			# This implementation supports a subset of the format: the default code
			# table, no secondary compression, and source windows which cover the
			# entire base. Unsupported features (secondary compression, custom code
			# tables, target windows as source) are rejected with explicit errors.
			module VCDiff
				# The magic bytes at the start of every delta: "VCD", 0.
				MAGIC = "\xD6\xC3\xC4\x00".b
				
				# The only supported format version.
				VERSION = 0
				
				# Hdr_Indicator bits:
				
				# The delta is compressed with a secondary compressor.
				VCD_DECOMPRESS = 0x01
				
				# The delta is preceded by a custom code table.
				VCD_CODETABLE = 0x02
				
				# Win_Indicator bits:
				
				# The window has a source segment.
				VCD_SOURCE = 0x01
				
				# The window has a target segment (the source is a preceding target).
				VCD_TARGET = 0x02
				
				# Instruction types:
				NOOP = 0
				ADD = 1
				RUN = 2
				COPY = 3
				
				# COPY address modes:
				SELF = 0
				HERE = 1
				NEAR_MODES = 2..5
				SAME_MODES = 6..8
				
				# Address cache sizes as per RFC 3284, section 5.2:
				NEAR_CACHE_SIZE = 4
				SAME_CACHE_SIZE = 3 * 256
				
				# The default code table from RFC 3284, section 5.3. Each entry maps
				# an opcode to up to two instructions: (type, size, mode) pairs. A
				# size of 0 means the size is encoded as a variable length integer
				# following the opcode.
				CODE_TABLE = begin
					table = []
					
					# Opcode 0: RUN, size encoded as a variable length integer.
					table << [RUN, 0, 0, NOOP, 0, 0]
					
					# Opcode 1: ADD, size encoded as a variable length integer.
					table << [ADD, 0, 0, NOOP, 0, 0]
					
					# Opcodes 2-17: ADD with implicit sizes 1-16.
					(1..16).each do |size|
						table << [ADD, size, 0, NOOP, 0, 0]
					end
					
					# Opcodes 18-170: COPY with implicit sizes 0-16 for modes 0-8.
					9.times do |mode|
						(0..16).each do |size|
							table << [COPY, size, mode, NOOP, 0, 0]
						end
					end
					
					# Opcodes 171-206: ADD (1-4) followed by COPY (4) for modes 0-8.
					9.times do |mode|
						(1..4).each do |add_size|
							table << [ADD, add_size, 0, COPY, 4, mode]
						end
					end
					
					# Opcodes 207-222: ADD (1-4) followed by COPY (5) for modes 0-3.
					4.times do |mode|
						(1..4).each do |add_size|
							table << [ADD, add_size, 0, COPY, 5, mode]
						end
					end
					
					# Opcodes 223-238: ADD (1) followed by COPY (6-9) for modes 0-3.
					4.times do |mode|
						(6..9).each do |copy_size|
							table << [ADD, 1, 0, COPY, copy_size, mode]
						end
					end
					
					# Opcodes 239-254: ADD (1-4) followed by COPY (4-7) for mode 6.
					(4..7).each do |copy_size|
						(1..4).each do |add_size|
							table << [ADD, add_size, 0, COPY, copy_size, 6]
						end
					end
					
					# Opcode 255: ADD (1) followed by COPY (8) for mode 6.
					table << [ADD, 1, 0, COPY, 8, 6]
					
					table.freeze
				end
				
				# The minimum length of a COPY instruction generated by the encoder.
				MINIMUM_MATCH = 4
				
				# The number of bytes used to index positions when matching.
				BLOCK_SIZE = 4
				
				# The maximum number of candidate positions considered per block.
				MAXIMUM_CANDIDATES = 16
				
				# Append an unsigned variable length integer to a buffer: 7 bits per
				# byte, big-endian, with the high bit set on all but the last byte.
				def self.write_varint(buffer, value)
					bytes = [value & 0x7F]
					value >>= 7
					
					while value > 0
						bytes.unshift((value & 0x7F) | 0x80)
						value >>= 7
					end
					
					buffer << bytes.pack("C*")
				end
				
				# Encode a target string as a delta against the given source (base)
				# string.
				#
				# @parameter source [String] The base instance.
				# @parameter target [String] The new instance.
				# @returns [String] The VCDIFF delta.
				def self.encode(source, target)
					Encoder.new(source, target).encode
				end
				
				# Decode a delta against the given source (base) string, producing
				# the target string.
				#
				# @parameter source [String] The base instance.
				# @parameter delta [String] The VCDIFF delta.
				# @returns [String] The reconstructed target instance.
				# @raises [Error] If the delta is malformed, uses unsupported
				#   features, or does not match the provided source.
				def self.decode(source, delta)
					Decoder.new(source).decode(delta)
				end
				
				# A cursor over a section of a delta.
				class Section
					def initialize(name, buffer)
						@name = name
						@buffer = buffer
						@offset = 0
					end
					
					# The current position within the buffer.
					attr :offset
					
					# The size of the buffer.
					def size
						@buffer.bytesize
					end
					
					# Whether the section has been fully consumed.
					def empty?
						@offset == @buffer.bytesize
					end
					
					def read_byte
						if @offset < @buffer.bytesize
							byte = @buffer.getbyte(@offset)
							@offset += 1
							return byte
						else
							raise Error, "Truncated #{@name} section!"
						end
					end
					
					def read_bytes(length)
						if @offset + length <= @buffer.bytesize
							bytes = @buffer.byteslice(@offset, length)
							@offset += length
							return bytes
						else
							raise Error, "Truncated #{@name} section!"
						end
					end
					
					def read_varint
						value = 0
						
						while true
							byte = read_byte
							value = (value << 7) | (byte & 0x7F)
							
							break if byte < 0x80
							
							if value > (1 << 56)
								raise Error, "Variable length integer is too large!"
							end
						end
						
						return value
					end
				end
				
				# Encodes a target string as a single-window delta against a source
				# string, using ADD instructions and COPY instructions with VCD_SELF
				# and VCD_HERE addresses.
				class Encoder
					def initialize(source, target)
						@source = source.b
						@target = target.b
						
						@instructions = String.new.b
						@addresses = String.new.b
						@data = String.new.b
					end
					
					def encode
						encode_instructions
						
						window = String.new.b
						
						if @source.empty?
							window << 0
						else
							window << VCD_SOURCE
							VCDiff.write_varint(window, @source.bytesize)
							VCDiff.write_varint(window, 0)
						end
						
						body = String.new.b
						VCDiff.write_varint(body, @target.bytesize)
						# Delta_Indicator: no secondary compression:
						body << 0
						VCDiff.write_varint(body, @data.bytesize)
						VCDiff.write_varint(body, @instructions.bytesize)
						VCDiff.write_varint(body, @addresses.bytesize)
						body << @data << @instructions << @addresses
						
						VCDiff.write_varint(window, body.bytesize)
						window << body
						
						header = String.new.b
						header << MAGIC << VERSION << 0
						header << window
						
						return header
					end
					
					private
					
					# Greedily match the target against the source window and the
					# target window generated so far, emitting ADD and COPY
					# instructions.
					def encode_instructions
						target_size = @target.bytesize
						
						# Index blocks of the source window; positions in the target
						# window are added as they are generated. Positions are stored
						# as unified addresses: the source window followed by the
						# target window.
						index = Hash.new {|hash, key| hash[key] = []}
						
						if @source.bytesize >= BLOCK_SIZE
							0.upto(@source.bytesize - BLOCK_SIZE) do |position|
								index[@source.byteslice(position, BLOCK_SIZE)] << position
							end
						end
						
						literal_start = 0
						position = 0
						
						while position < target_size
							if match = find_match(index, position)
								length, address = match
								
								emit_add(literal_start...position)
								emit_copy(address, length, position)
								
								length.times do |offset|
									insert_index(index, position + offset)
								end
								
								position += length
								literal_start = position
							else
								insert_index(index, position)
								position += 1
							end
						end
						
						emit_add(literal_start...target_size)
					end
					
					def insert_index(index, position)
						if position + BLOCK_SIZE <= @target.bytesize
							key = @target.byteslice(position, BLOCK_SIZE)
							index[key] << (@source.bytesize + position)
						end
					end
					
					# Find the longest match for the target at the given position, in
					# either the source window or the target window generated so far.
					# Returns [length, unified address] or nil.
					def find_match(index, position)
						if position + BLOCK_SIZE > @target.bytesize
							return nil
						end
						
						key = @target.byteslice(position, BLOCK_SIZE)
						candidates = index[key]
						
						if candidates.empty?
							return nil
						end
						
						best_length = 0
						best_address = nil
						
						# Consider the most recently indexed candidates first:
						candidates.last(MAXIMUM_CANDIDATES).each do |address|
							length = match_length(address, position)
							
							if length > best_length
								best_length = length
								best_address = address
							end
						end
						
						if best_length >= MINIMUM_MATCH
							return best_length, best_address
						else
							return nil
						end
					end
					
					# Compute the length of the match between the unified window at
					# the given address and the target at the given position.
					def match_length(address, position)
						source_size = @source.bytesize
						target_size = @target.bytesize
						
						if address < source_size
							# Matches in the source window are limited by its end:
							limit = source_size - address
						else
							# Matches in the target window may overlap the current
							# position, as overlapping copies are expanded byte by
							# byte when decoding:
							limit = target_size - position
						end
						
						if limit > target_size - position
							limit = target_size - position
						end
						
						length = 0
						
						while length < limit
							if address < source_size
								break unless @source.getbyte(address + length) == @target.getbyte(position + length)
							else
								break unless @target.getbyte(address - source_size + length) == @target.getbyte(position + length)
							end
							
							length += 1
						end
						
						return length
					end
					
					def emit_add(range)
						return if range.begin == range.end
						
						length = range.size
						
						if length <= 16
							# ADD with implicit size:
							@instructions << (length + 1)
						else
							# ADD with size encoded as a variable length integer:
							@instructions << 1
							VCDiff.write_varint(@instructions, length)
						end
						
						@data << @target.byteslice(range.begin, length)
					end
					
					def emit_copy(address, length, position)
						if address < @source.bytesize
							# Copy from the source window (VCD_SELF):
							mode = SELF
							value = address
						else
							# Copy from the target window (VCD_HERE):
							mode = HERE
							value = (@source.bytesize + position) - address
						end
						
						if length <= 16
							# COPY with implicit size:
							@instructions << (18 + (mode * 17) + length)
						else
							# COPY with size encoded as a variable length integer:
							@instructions << (18 + (mode * 17))
							VCDiff.write_varint(@instructions, length)
						end
						
						VCDiff.write_varint(@addresses, value)
					end
				end
				
				# Decodes a delta against a source (base) string. The source window
				# of every window must cover the entire source, which ensures a
				# mismatched base is rejected rather than silently producing a
				# corrupt target.
				class Decoder
					def initialize(source)
						@source = source.b
					end
					
					def decode(delta)
						section = Section.new("delta", delta.b)
						
						read_header(section)
						
						output = String.new.b
						
						until section.empty?
							output << decode_window(section)
						end
						
						return output
					end
					
					private
					
					def read_header(section)
						magic = section.read_bytes(4)
						
						unless magic == MAGIC
							raise Error, "Invalid magic bytes!"
						end
						
						version = section.read_byte
						
						unless version == VERSION
							raise Error, "Unsupported VCDIFF version: #{version}!"
						end
						
						indicator = section.read_byte
						
						if indicator & VCD_DECOMPRESS != 0
							raise Error, "Secondary compression (VCD_DECOMPRESS) is not supported!"
						end
						
						if indicator & VCD_CODETABLE != 0
							raise Error, "Custom code tables (VCD_CODETABLE) are not supported!"
						end
						
						unless indicator == 0
							raise Error, "Unsupported header indicator: #{indicator}!"
						end
					end
					
					def decode_window(section)
						indicator = section.read_byte
						
						if indicator & VCD_TARGET != 0
							raise Error, "Target windows as source (VCD_TARGET) are not supported!"
						end
						
						if indicator & VCD_SOURCE != 0
							source_length = section.read_varint
							source_position = section.read_varint
							
							unless source_position == 0 and source_length == @source.bytesize
								raise Error, "Source window mismatch: expected #{@source.bytesize} bytes at position 0, got #{source_length} bytes at position #{source_position}!"
							end
						else
							unless @source.empty?
								raise Error, "Delta does not reference the provided base!"
							end
						end
						
						delta_length = section.read_varint
						window_end = section.offset + delta_length
						
						if window_end > section.size
							raise Error, "Window extends past the end of the delta!"
						end
						
						target_length = section.read_varint
						
						delta_indicator = section.read_byte
						
						unless delta_indicator == 0
							raise Error, "Secondary compression of delta sections is not supported!"
						end
						
						data_length = section.read_varint
						instructions_length = section.read_varint
						addresses_length = section.read_varint
						
						data = Section.new("data", section.read_bytes(data_length))
						instructions = Section.new("instructions", section.read_bytes(instructions_length))
						addresses = Section.new("addresses", section.read_bytes(addresses_length))
						
						target = execute(target_length, data, instructions, addresses)
						
						unless section.offset == window_end
							raise Error, "Window sections do not match the window length!"
						end
						
						return target
					end
					
					def execute(target_length, data, instructions, addresses)
						target = String.new.b
						
						near_cache = Array.new(NEAR_CACHE_SIZE, 0)
						same_cache = Array.new(SAME_CACHE_SIZE, 0)
						
						until instructions.empty?
							opcode = instructions.read_byte
							entry = CODE_TABLE[opcode]
							
							2.times do |index|
								type = entry[index * 3]
								size = entry[index * 3 + 1]
								mode = entry[index * 3 + 2]
								
								next if type == NOOP
								
								if size == 0
									size = instructions.read_varint
								end
								
								case type
								when ADD
									target << data.read_bytes(size)
								when RUN
									target << data.read_byte.chr * size
								when COPY
									address = decode_address(mode, addresses, target.bytesize, near_cache, same_cache)
									
									copy(target, address, size)
									
									# Update the address caches:
									near_cache.unshift(address)
									near_cache.pop
									same_cache[address % SAME_CACHE_SIZE] = address
								end
								
								if target.bytesize > target_length
									raise Error, "Target window overflow!"
								end
							end
						end
						
						unless target.bytesize == target_length
							raise Error, "Target window size mismatch: expected #{target_length} bytes, got #{target.bytesize}!"
						end
						
						unless data.empty? and addresses.empty?
							raise Error, "Trailing data in delta sections!"
						end
						
						return target
					end
					
					def decode_address(mode, addresses, target_size, near_cache, same_cache)
						case mode
						when SELF
							addresses.read_varint
						when HERE
							distance = addresses.read_varint
							limit = @source.bytesize + target_size
							
							if distance > limit
								raise Error, "Invalid VCD_HERE address: #{distance}!"
							end
							
							limit - distance
						when NEAR_MODES
							near_cache[mode - 2] + addresses.read_varint
						when SAME_MODES
							same_cache[(mode - 6) * 256 + addresses.read_byte]
						else
							raise Error, "Invalid address mode: #{mode}!"
						end
					end
					
					# Copy size bytes from the unified window (the source window
					# followed by the target window generated so far) at the given
					# address, appending them to the target.
					def copy(target, address, size)
						return if size == 0
						
						source_size = @source.bytesize
						available = source_size + target.bytesize
						
						if address >= available
							raise Error, "COPY address #{address} is out of range!"
						end
						
						if address + size <= source_size
							# The copy is entirely within the source window:
							target << @source.byteslice(address, size)
						else
							# Copy byte by byte, allowing the copy to overlap the
							# target window generated so far:
							size.times do
								if address < source_size
									target << @source.getbyte(address)
								else
									target << target.getbyte(address - source_size)
								end
								
								address += 1
							end
						end
					end
				end
			end
		end
	end
end
